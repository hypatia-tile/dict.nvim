describe("dict", function()
  local dict = require("dict")
  it("returns a table when required", function()
    assert.is_table(dict)
  end)
  it("dict has a setup function", function()
    assert.is_function(dict.setup)
  end)
end)

describe("dict.setup", function()
  local dict = require("dict")
  it("backend is a function", function()
    dict.setup()
    assert.is_function(dict.backend)
  end)
  it("set default databases", function()
    dict.setup()
    local dbs = dict.databases
    assert.is_table(dbs)
    assert.equal("wn", dbs[1], "dbs[1] is 'wn'")
    assert.equal("wiktionary", dbs[2], "dbs[2] is 'wiktionary'")
  end)
end)
